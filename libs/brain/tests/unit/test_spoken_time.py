"""Момент из фразы кодом: день, время, часть суток, ближайшее будущее и что отдаётся модели."""

from datetime import datetime

import pytest

from brain.spoken_time import spokenMoment

MSK = "Europe/Moscow"
NIGHT = "2026-10-26T00:42:00+03:00"
MORNING = "2026-10-26T10:00:00+03:00"
EVENING = "2026-10-26T19:30:00+03:00"
LATE = "2026-10-25T23:42:00+03:00"


@pytest.mark.parametrize(
    ("now", "text", "expected", "dayNamed"),
    [
        # без дня — ближайший ещё не наступивший момент
        (NIGHT, "В 5 позвонить бабушке", "2026-10-26T05:00:00+03:00", False),
        (MORNING, "Напомни в 2 помыть машину", "2026-10-26T14:00:00+03:00", False),
        (MORNING, "В 5 позвонить бабушке", "2026-10-26T17:00:00+03:00", False),
        (EVENING, "в 5 позвонить", "2026-10-27T05:00:00+03:00", False),
        (LATE, "в 12 лечь спать", "2026-10-26T00:00:00+03:00", False),
        (MORNING, "в 12 обед", "2026-10-26T12:00:00+03:00", False),
        (MORNING, "встреча в 17:30", "2026-10-26T17:30:00+03:00", False),
        (MORNING, "в 3 часа созвон", "2026-10-26T15:00:00+03:00", False),
        (EVENING, "в 7 утра пробежка", "2026-10-27T07:00:00+03:00", False),
        (MORNING, "в 9 вечера кино", "2026-10-26T21:00:00+03:00", False),
        # день назван: 7–11 утро, 1–6 день, часть суток важнее
        (MORNING, "послезавтра в 10 банк", "2026-10-28T10:00:00+03:00", True),
        (MORNING, "встреча с Петром послезавтра в 3", "2026-10-28T15:00:00+03:00", True),
        (EVENING, "напомни через неделю в 9 купить молоко", "2026-11-02T09:00:00+03:00", True),
        (EVENING, "через две недели в 18 встреча", "2026-11-09T18:00:00+03:00", True),
        (MORNING, "через 3 дня в 10 оплатить", "2026-10-29T10:00:00+03:00", True),
        (MORNING, "через день в 8 зарядка", "2026-10-27T08:00:00+03:00", True),
        (MORNING, "завтра в 5 вечера", "2026-10-27T17:00:00+03:00", True),
        (MORNING, "завтра в 2 ночи", "2026-10-27T02:00:00+03:00", True),
        (MORNING, "завтра в 11 ночи", "2026-10-27T23:00:00+03:00", True),
        (MORNING, "сегодня в 6", "2026-10-26T18:00:00+03:00", True),
        # ночью «завтра» — наступающий день, то есть сегодняшняя дата
        (NIGHT, "завтра в 10 созвон", "2026-10-26T10:00:00+03:00", True),
        # конец месяца и года; «сейчас» в UTC
        ("2026-12-31T20:00:00+03:00", "через неделю в 10", "2027-01-07T10:00:00+03:00", True),
        ("2026-10-25T21:42:00+00:00", "в 5", "2026-10-26T05:00:00+03:00", False),
    ],
)
def test_spokenMoment(now: str, text: str, expected: str, dayNamed: bool) -> None:
    spoken = spokenMoment(text, datetime.fromisoformat(now), MSK)
    assert spoken is not None
    assert (spoken.moment.isoformat(), spoken.dayNamed) == (expected, dayNamed)


@pytest.mark.parametrize(
    ("now", "text"),
    [
        (MORNING, "в пятницу в 5 отчёт"),
        (MORNING, "встреча 28.10 в 15"),
        (MORNING, "через 2 часа в 5"),
        (MORNING, "через пару дней в 5"),
        (MORNING, "на следующей неделе в 10"),
        (MORNING, "с 5 до 6 в 7 созвон в 8"),
        (MORNING, "напомни через 5 минут"),
        (MORNING, "напомни купить хлеб"),
        (MORNING, "в 25 часов"),
        (MORNING, "сегодня завтра в 10"),
        # день назван, а момент прошёл — про прошлое говорит модель
        (LATE, "сегодня в 7 позвонить"),
    ],
)
def test_leftToModel(now: str, text: str) -> None:
    assert spokenMoment(text, datetime.fromisoformat(now), MSK) is None
