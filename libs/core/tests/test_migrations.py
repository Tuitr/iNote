import asyncio
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import inspect
from sqlalchemy.engine import URL, Connection

from libs.core.resources import create_db_engine

ALEMBIC_INI = Path(__file__).resolve().parents[3] / "alembic.ini"
TABLES = {"users", "items", "notifications", "dialog_log"}


def _schema(database_url: str) -> dict[str, set[str]]:
    """Таблицы и имена их индексов, кроме служебной alembic_version.

    Индексы, которые PostgreSQL сам создаёт под unique-ограничения, не считаются.
    """

    def read(connection: Connection) -> dict[str, set[str]]:
        inspector = inspect(connection)
        return {
            table: {
                index["name"]
                for index in inspector.get_indexes(table)
                if "duplicates_constraint" not in index
            }
            for table in inspector.get_table_names()
            if table != "alembic_version"
        }

    async def scenario() -> dict[str, set[str]]:
        engine = create_db_engine(database_url)
        try:
            async with engine.connect() as connection:
                return await connection.run_sync(read)
        finally:
            await engine.dispose()

    return asyncio.run(scenario())


def test_migrations_build_schema_from_scratch_and_roll_back(
    test_database_url: URL, monkeypatch: pytest.MonkeyPatch
) -> None:
    database_url = test_database_url.render_as_string(hide_password=False)
    monkeypatch.setenv("DATABASE_URL", database_url)
    config = Config(str(ALEMBIC_INI))

    command.downgrade(config, "base")
    assert _schema(database_url) == {}

    command.upgrade(config, "head")
    schema = _schema(database_url)
    assert set(schema) == TABLES
    assert schema["items"] == {
        "ix_items_user_id_starts_at",
        "ix_items_search_tsv",
        "ix_items_title_trgm",
    }
    assert schema["notifications"] == {"ix_notifications_fire_at"}
    # Модели SQLAlchemy совпадают со схемой из миграций, иначе AutogenerateDiffsDetected.
    command.check(config)

    command.downgrade(config, "base")
    assert _schema(database_url) == {}

    # Остальные тесты с базой ждут схему на месте.
    command.upgrade(config, "head")
